#!/usr/bin/env python3
"""Reproduce all 49 manual HUD composition decisions and the initial six trials.

CPU/Pillow compositions only: these are not Godot screenshots or GPU acceptance.
Run: python tools/preview_portrait_crops.py --write-runtime
Later: python tools/preview_portrait_crops.py --check-runtime
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "assets/portraits/hud_crops.json"
RUNTIME = ROOT / "scenes/ui/creature_portrait_crops.gd"
OUTPUT = ROOT / "docs/audits/2026-11-06-portrait-crops"
BG = "#111923"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def source_hashes():
    # Exactly the 49 runtime IDs, not unrelated concept experiments in the folder.
    names = sorted(p.name for p in (ROOT / "assets/portraits/creatures").glob("*.png"))
    assert len(names) == 49, f"Expected 49 runtime references, found {len(names)}"
    paths = [ROOT / folder / name for folder in ["assets/portraits/creatures", "tools/ai_models/concepts"] for name in names]
    return {str(p.relative_to(ROOT)): digest(p) for p in paths}


def runtime_text(data):
    lines = ["extends RefCounted", "## Generated by tools/preview_portrait_crops.py from hud_crops.json.",
             "## Individual Sol-reviewed CPU compositions; GPU acceptance pending. HUD scope only.",
             "const COORDINATE_SIZE := Vector2(256, 256)", "const REGIONS := {"]
    for key, row in data["candidates"].items():
        if not row["enabled"]:
            continue
        region = ", ".join(str(n) for n in row["region"])
        lines.append(f'\t&"{key}": Rect2({region}),')
    return "\n".join(lines + ["}", ""])


def font(size):
    return ImageFont.truetype("DejaVuSans.ttf", size)


def panel_preview(image72, stem):
    """156px production dimensions/palette; CPU text layout is illustrative."""
    panel = Image.new("RGB", (156, 156), "#050b11")
    draw = ImageDraw.Draw(panel)
    draw.rounded_rectangle((0, 0, 155, 155), radius=3, fill="#050b11", outline="#337a87", width=1)
    draw.line((3, 1, 152, 1), fill="#337a87", width=3)
    panel.paste(image72, (6, 20))
    names = {"dragnar": "Драгнар", "klykar": "Клыкар", "kolossar": "Колоссар", "levian": "Левиан", "ratnik": "Ратник", "likorez": "Ликорез"}
    elements = {"fire": "Огонь", "gale": "Буря", "shadow": "Тень", "light": "Свет"}
    species, element = stem.split("_")
    body = ImageFont.truetype(str(ROOT / "assets/fonts/FiraSans-Regular.ttf"), 14)
    # CPU wrapping approximates the real 68px identity column, explicitly not a UI capture.
    title = names[species]
    if draw.textlength(title, font=body) > 68:
        title = title[:5] + "\n" + title[5:]
    draw.multiline_text((116, 36), title, font=body, fill="#f5eddb", anchor="mm", align="center", spacing=2)
    draw.text((116, 73), elements[element], font=body, fill="#66f0ed", anchor="mm")
    power = ImageFont.truetype(str(ROOT / "assets/fonts/FiraSans-Regular.ttf"), 28)
    draw.text((78, 131), "420 G", font=power, fill="#66f0ed", anchor="mm")
    return panel


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUTPUT)
    parser.add_argument("--write-runtime", action="store_true", help="Regenerate the small literal runtime table")
    parser.add_argument("--check-runtime", action="store_true", help="Require exact JSON / GDScript correspondence")
    args = parser.parse_args()
    data = json.loads(MANIFEST.read_text())
    assert data["schema"] == 1 and data["coordinate_space"] == [256, 256]
    assert data["preview_px"] == 72 and len(data["candidates"]) == 49
    before = source_hashes()
    generated = runtime_text(data)
    if args.write_runtime:
        RUNTIME.write_text(generated)
    if args.check_runtime:
        assert RUNTIME.read_text() == generated, "Runtime table differs; inspect manifest then --write-runtime"
    args.out.mkdir(parents=True, exist_ok=True)
    sheet = Image.new("RGB", (1152, 1188), BG)
    panels = Image.new("RGB", (750, 1250), BG)
    panels_draw = ImageDraw.Draw(panels)
    panels_draw.text((20, 12), "A05 | 156px panel / 72px image | CPU mockup", font=font(20), fill="white")
    panels_draw.text((20, 43), "Production palette, dimensions, FiraSans. Text layout approximate; not Godot/GPU.", font=font(14), fill="#bed0dd")
    catalog = Image.new("RGB", (1200, 1845), BG)
    catdraw = ImageDraw.Draw(catalog)
    catdraw.text((16, 10), "ALL 49 MANUAL DECISIONS | before / proposed at actual 72px | CPU only / GPU pending", font=font(18), fill="white")
    catdraw.text((16, 36), "42 selected head / upper-body crops; 7 retained full-body. Each ID inspected individually. White background preserved.", font=font(14), fill="#bed0dd")
    boundaries = Image.new("RGB", (1120, 1290), BG)
    boundarydraw = ImageDraw.Draw(boundaries)
    boundarydraw.text((12, 10), "49 MANUAL CROP BOUNDS | source 256px shown at 144px | cyan = selected crop, gray = keep full", font=font(17), fill="white")
    draw = ImageDraw.Draw(sheet)
    draw.text((20, 12), "A05 | SIX MANUAL HUD CROP TRIALS | Sol CPU review / GPU pending", font=font(20), fill="white")
    draw.text((20, 43), "CPU/Pillow composition from existing 256px references. Not Godot/GPU. White source background preserved.", font=font(14), fill="#bed0dd")
    rows = []
    trial_index = {key: index for index, key in enumerate(data["initial_trial_ids"])}
    for catalog_index, (key, entry) in enumerate(data["candidates"].items()):
        stem = key.removeprefix("creature_")
        source_path = ROOT / "assets/portraits/creatures" / f"{stem}.png"
        source = Image.open(source_path).convert("RGB")
        assert source.size == (256, 256)
        x, y, w, h = entry["region"]
        assert all(type(n) is int for n in entry["region"])
        assert w == h and w > 0 and min(x, y) >= 0 and x + w <= 256 and y + h <= 256
        crop = source.crop((x, y, x + w, y + h))
        full72 = source.resize((72, 72), Image.Resampling.BILINEAR)
        crop72 = crop.resize((72, 72), Image.Resampling.BILINEAR)
        proposed72 = crop72 if entry["enabled"] else full72
        cat_x, cat_y = (catalog_index % 4) * 300 + 16, (catalog_index // 4) * 136 + 70
        catdraw.text((cat_x, cat_y), stem, font=font(14), fill="white")
        catalog.paste(full72, (cat_x, cat_y + 24))
        catalog.paste(proposed72, (cat_x + 94, cat_y + 24))
        catdraw.text((cat_x, cat_y + 103), "full", font=font(12), fill="#bed0dd")
        decision = f"crop {256 / w:.2f}x" if entry["enabled"] else "KEEP FULL"
        catdraw.text((cat_x + 94, cat_y + 103), decision, font=font(12), fill="#66dce7" if entry["enabled"] else "#bed0dd")
        marked = source.copy()
        bounds = (x, y, x + w - 1, y + h - 1) if entry["enabled"] else (0, 0, 255, 255)
        ImageDraw.Draw(marked).rectangle(bounds, outline="#00b2cc" if entry["enabled"] else "#666666", width=3)
        bx, by = (catalog_index % 7) * 160 + 8, (catalog_index // 7) * 178 + 44
        boundaries.paste(marked.resize((144, 144), Image.Resampling.BILINEAR), (bx, by))
        boundarydraw.text((bx, by + 147), stem, font=font(11), fill="white")
        rows.append({"id": key, "enabled": entry["enabled"], "region": entry["region"], "scale": round(256 / w, 4), "intent": entry["intent"]})
        if key not in trial_index:
            continue
        index = trial_index[key]
        # Actual 72px files are separate from the labelled comparison sheet.
        full72.save(args.out / f"{stem}-full72.png")
        crop72.save(args.out / f"{stem}-crop72.png")
        panel_y = 90 + index * 190
        panels_draw.text((20, panel_y + 65), stem, font=font(17), fill="white")
        panels.paste(panel_preview(full72, stem), (350, panel_y))
        panels.paste(panel_preview(crop72, stem), (560, panel_y))
        if index == 0:
            panels_draw.text((350, 68), "full body", font=font(14), fill="#bed0dd")
            panels_draw.text((560, 68), "manual crop", font=font(14), fill="#bed0dd")
        row_y = 82 + index * 182
        draw.text((20, row_y), stem, font=font(18), fill="white")
        marked = source.copy()
        ImageDraw.Draw(marked).rectangle((x, y, x + w - 1, y + h - 1), outline="#00b2cc", width=3)
        sheet.paste(marked.resize((144, 144), Image.Resampling.BILINEAR), (20, row_y + 27))
        sheet.paste(full72, (195, row_y + 58))
        sheet.paste(crop72, (300, row_y + 58))
        sheet.paste(crop72.resize((144, 144), Image.Resampling.NEAREST), (408, row_y + 27))
        draw.text((188, row_y + 30), "full 72px", font=font(13), fill="#bed0dd")
        draw.text((293, row_y + 30), "crop 72px", font=font(13), fill="#bed0dd")
        draw.text((410, row_y + 5), "crop 2x pixels", font=font(13), fill="#bed0dd")
        draw.text((580, row_y + 35), f"region [{x}, {y}, {w}, {h}] | {256 / w:.2f}x image scale", font=font(15), fill="#66dce7")
        # Keep simple wrapped prose legible on the comparison sheet.
        words, lines = entry["intent"].split(), []
        line = ""
        for word in words:
            trial = (line + " " + word).strip()
            if draw.textlength(trial, font=font(14)) > 545:
                lines.append(line)
                line = word
            else:
                line = trial
        lines.append(line)
        for line_index, line in enumerate(lines):
            draw.text((580, row_y + 68 + line_index * 23), line, font=font(14), fill="#dbe5ee")
    sheet.save(args.out / "comparison.png")
    panels.save(args.out / "panels156.png")
    catalog.save(args.out / "catalog49-before-after72.png")
    boundaries.save(args.out / "catalog49-crop-bounds.png")
    after = source_hashes()
    assert before == after, "Source images changed during preview generation"
    report = {"status": data["status"], "method": "CPU Pillow bilinear resize; manual regions; no source pixel edits",
              "godot_capture": False, "gpu_acceptance": False, "production_enabled_count": sum(row["enabled"] for row in rows),
              "display_px": 72, "candidate_count": len(rows), "sources_unchanged": before == after,
              "source_hashes_before": before, "source_hashes_after": after,
              "manifest_sha256": digest(MANIFEST), "runtime_table_sha256": digest(RUNTIME), "candidates": rows}
    (args.out / "evidence.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    print(f"49 manual decisions / 6 initial trials at 72px; 98 source hashes unchanged; output: {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}")


if __name__ == "__main__":
    main()
